package com.example.travel.observability;

import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.Timer;
import org.springframework.stereotype.Service;
import org.springframework.beans.factory.annotation.Autowired;

import java.time.Duration;
import java.util.Locale;
import java.util.Set;

/**
 * Central metrics facade for agent execution.
 *
 * <p>Only low-cardinality dimensions are used as metric tags. User ids,
 * thread ids, prompts, arguments and error messages must stay out of metric
 * labels; those belong in structured logs/traces.</p>
 */
@Service
public class AgentObservabilityService {

    private static final Set<String> REPLAN_REASONS = Set.of(
            "max_retries_exhausted", "user_modification", "goal_not_achieved",
            "goal_validation_failed");
    private static final Set<String> RETRY_REASONS = Set.of(
            "timeout", "connect", "io", "http", "interrupted", "other");
    private static final Set<String> RETRY_CATEGORIES = Set.of("mcp", "llm", "provider", "graph");
    private final MeterRegistry registry;
    private final AgentRuntimeEventLedger runtimeEvents;

    @Autowired
    public AgentObservabilityService(MeterRegistry registry, AgentRuntimeEventLedger runtimeEvents) {
        this.registry = registry;
        this.runtimeEvents = runtimeEvents;
    }

    /** Test/backwards-compatible constructor; Spring uses the fully wired constructor above. */
    public AgentObservabilityService(MeterRegistry registry) {
        this.registry = registry;
        this.runtimeEvents = null;
    }

    private void runtime(String type, String component, boolean success, long durationMs, int attempt) {
        if (runtimeEvents != null) runtimeEvents.recordCurrentRun(type, component,
                success ? "SUCCESS" : "ERROR", durationMs, attempt);
    }

    public void recordLlmCall(String operation, String model, int inputTokens,
                              int outputTokens, long durationMs, boolean success) {
        runtime("LLM", model, success, durationMs, 1);
        String safeOperation = normalize(operation);
        String safeModel = normalize(model);

        Counter.builder("agent.llm.calls")
                .description("LLM calls made by the agent")
                .tag("operation", safeOperation)
                .tag("model", safeModel)
                .tag("status", success ? "success" : "error")
                .register(registry)
                .increment();

        Counter.builder("agent.llm.tokens.input")
                .description("Input tokens consumed by LLM calls")
                .tag("operation", safeOperation)
                .tag("model", safeModel)
                .register(registry)
                .increment(Math.max(0, inputTokens));

        Counter.builder("agent.llm.tokens.output")
                .description("Output tokens generated by LLM calls")
                .tag("operation", safeOperation)
                .tag("model", safeModel)
                .register(registry)
                .increment(Math.max(0, outputTokens));

        Timer.builder("agent.llm.duration")
                .description("LLM call duration")
                .tag("operation", safeOperation)
                .tag("model", safeModel)
                .register(registry)
                .record(Duration.ofMillis(Math.max(0, durationMs)));
    }

    public void recordLlmBudgetExhausted(String operation) {
        Counter.builder("agent.llm.budget.exhausted")
                .description("LLM execution budget exhaustion events")
                .tag("operation", normalize(operation))
                .register(registry)
                .increment();
    }

    public void recordMcpCall(String tool, long durationMs, boolean success, int attempt) {
        runtime("MCP", tool, success, durationMs, attempt);
        String safeTool = normalize(tool);

        Counter.builder("agent.mcp.calls")
                .description("MCP tool invocations")
                .tag("tool", safeTool)
                .tag("status", success ? "success" : "error")
                .register(registry)
                .increment();

        Timer.builder("agent.mcp.duration")
                .description("MCP tool invocation duration")
                .tag("tool", safeTool)
                .register(registry)
                .record(Duration.ofMillis(Math.max(0, durationMs)));

        if (attempt > 1) {
            Counter.builder("agent.mcp.retries")
                    .description("MCP retry attempts")
                    .tag("tool", safeTool)
                    .register(registry)
                    .increment();
        }
    }

    public void recordMcpPolicyDecision(String tool, String decision) {
        Counter.builder("agent.mcp.policy.decisions")
                .description("MCP governance decisions")
                .tag("tool", normalize(tool))
                .tag("decision", normalize(decision))
                .register(registry)
                .increment();
    }

    public void recordRetry(String category, String reason) {
        String safeCategory = boundedCategory(category);
        String safeReason = retryReason(reason);
        runtime("RETRY", safeCategory + ":" + safeReason, true, 0, 2);
        Counter.builder("agent.retries")
                .description("Agent and provider retry attempts")
                .tag("category", safeCategory)
                .tag("reason", safeReason)
                .register(registry)
                .increment();
    }

    public void recordReplan(String reason) {
        String safeReason = boundedReplanReason(reason);
        runtime("REPLAN", safeReason, true, 0, 1);
        Counter.builder("agent.replans")
                .description("Agent replans")
                .tag("reason", safeReason)
                .register(registry)
                .increment();
    }

    public void recordNode(String node, long durationMs, boolean success) {
        runtime("NODE", node, success, durationMs, 1);
        Counter.builder("agent.nodes")
                .description("Agent graph node executions")
                .tag("node", normalize(node))
                .tag("status", success ? "success" : "error")
                .register(registry)
                .increment();

        Timer.builder("agent.node.duration")
                .description("Agent graph node duration")
                .tag("node", normalize(node))
                .register(registry)
                .record(Duration.ofMillis(Math.max(0, durationMs)));
    }

    public void recordProviderCall(String provider, String operation, long durationMs, boolean success) {
        runtime("PROVIDER", provider + ":" + operation, success, durationMs, 1);
        Counter.builder("agent.provider.calls")
                .description("External provider calls")
                .tag("provider", normalize(provider))
                .tag("operation", normalize(operation))
                .tag("status", success ? "success" : "error")
                .register(registry)
                .increment();

        Timer.builder("agent.provider.duration")
                .description("External provider call duration")
                .tag("provider", normalize(provider))
                .tag("operation", normalize(operation))
                .register(registry)
                .record(Duration.ofMillis(Math.max(0, durationMs)));
    }

    public void recordJevDecision(String decisionType, String outcome, String model, long durationMs) {
        Counter.builder("agent.jev.decisions").description("Jev typed decisions")
                .tag("type", normalize(decisionType)).tag("outcome", normalize(outcome)).tag("model", normalize(model))
                .register(registry).increment();
        Timer.builder("agent.jev.duration").description("Jev decision latency")
                .tag("type", normalize(decisionType)).register(registry)
                .record(Duration.ofMillis(Math.max(0, durationMs)));
    }

    public void recordGoalOutcome(String outcome) {
        Counter.builder("agent.goal.outcomes")
                .description("Agent goal outcomes")
                .tag("outcome", normalize(outcome))
                .register(registry)
                .increment();
    }

    public void recordRun(String status, long durationMs) {
        runtime("RUN", "agent-run", "success".equalsIgnoreCase(status) || "achieved".equalsIgnoreCase(status), durationMs, 1);
        Counter.builder("agent.runs")
                .description("Agent runs")
                .tag("status", normalize(status))
                .register(registry)
                .increment();

        Timer.builder("agent.run.duration")
                .description("End-to-end agent run duration")
                .register(registry)
                .record(Duration.ofMillis(Math.max(0, durationMs)));
    }

    private static String normalize(String value) {
        if (value == null || value.isBlank()) return "unknown";
        return value.trim().toLowerCase(Locale.ROOT)
                .replaceAll("[^a-z0-9_.-]", "_");
    }

    private static String boundedCategory(String value) {
        String normalized = normalize(value);
        return RETRY_CATEGORIES.contains(normalized)
                ? normalized : "other";
    }

    private static String retryReason(String value) {
        if (value == null || value.isBlank()) return "other";
        String simple = value.trim().toLowerCase(Locale.ROOT);
        if (simple.contains("timeout")) return "timeout";
        if (simple.contains("connect")) return "connect";
        if (simple.contains("interrupt")) return "interrupted";
        if (simple.contains("http") || simple.contains("status")) return "http";
        if (simple.contains("socket") || simple.endsWith("ioexception")) return "io";
        return RETRY_REASONS.contains(simple) ? simple : "other";
    }

    private static String boundedReplanReason(String value) {
        String normalized = normalize(value);
        return REPLAN_REASONS.contains(normalized) ? normalized : "other";
    }
}
